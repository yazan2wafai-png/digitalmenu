export type AdminTranslations = {
  [K in keyof typeof adminTranslations.tr]: {
    [P in keyof (typeof adminTranslations.tr)[K]]: string;
  };
};

interface AdminI18nContextType {
  locale: AdminLocale;
  setLocale: (locale: AdminLocale) => void;
  t: AdminTranslations;
}

const AdminI18nContext = createContext<AdminI18nContextType>({
  locale: 'tr',
  setLocale: () => {},
  t: adminTranslations.tr,
});

export function AdminI18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<AdminLocale>('tr');

  useEffect(() => {
    try {
      const saved = localStorage.getItem(ADMIN_I18N_STORAGE_KEY) as AdminLocale | null;
      if (saved === 'tr' || saved === 'en') {
        setLocaleState(saved);
      }
    } catch {
      // localStorage may not be available
    }
  }, []);

  const setLocale = useCallback((newLocale: AdminLocale) => {
    setLocaleState(newLocale);
    try {
      localStorage.setItem(ADMIN_I18N_STORAGE_KEY, newLocale);
    } catch {
      // Ignore
    }
  }, []);

  const value = {
    locale,
    setLocale,
    t: adminTranslations[locale],
  };

  return (
    <AdminI18nContext.Provider value={value}>
      {children}
    </AdminI18nContext.Provider>
  );
}

export function useAdminI18n() {
  return useContext(AdminI18nContext);
}
